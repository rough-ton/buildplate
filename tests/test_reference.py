def _fake_model(monkeypatch, script):
    import litellm

    calls = iter(script)
    seen = []

    async def acompletion(**kw):
        seen.append(json.loads(json.dumps(kw["messages"])))
        tcs = [SimpleNamespace(id=f"t{n}", function=SimpleNamespace(name=name, arguments=json.dumps(args)))
               for n, (name, args) in enumerate(next(calls))]
        msg = SimpleNamespace(content="", tool_calls=tcs)
        return SimpleNamespace(choices=[SimpleNamespace(message=msg)], usage=SimpleNamespace(prompt_tokens=100, completion_tokens=20))

    monkeypatch.setattr(litellm, "acompletion", acompletion)
    return seen


SUBMIT = [[("submit_design", {"code": "cube([20,10,5]);", "title": "Block", "summary": "A block."})]]


def _run(env, prompt, **kw):
    events = []

    async def go():
        async for ev in env.agent.run(prompt, **kw):
            events.append(ev)

    asyncio.run(go())
    return events


def _ollama(env, vision):
    c = env.connections.create("ollama.local", "Box", {"base_url": "http://box:11434"})
    env.store.update({"agent": {"connection": c["id"], "model": "qwen3", "vision": vision}})
    return c


def test_picture_goes_to_vision_models_as_an_image(env, monkeypatch):
    _ollama(env, "on")
    r = save(env, "photo.png", _png())
    seen = _fake_model(monkeypatch, SUBMIT)
    events = _run(env, "make this bracket", reference=r["id"])
    assert events[-1]["type"] == "done"
    ref_ev = next(e for e in events if e["type"] == "reference")
    assert ref_ev["image_sent"] and ref_ev["reference"]["name"] == "photo.png"
    request = seen[0][-1]
    assert request["role"] == "user" and isinstance(request["content"], list)
    text, image = request["content"]
    assert text["text"].startswith("Design request: make this bracket") and "Reference: photo.png (picture)" in text["text"]
    assert image["image_url"]["url"].startswith("data:image/png;base64,")
    # the transcript keeps the reference with the user's message
    msgs = env.db.get_design(events[-1]["design_id"])["messages"]
    assert msgs[0]["reference"]["id"] == r["id"] and msgs[0]["reference"]["image_url"]
    assert msgs[1]["reference"] is None


def test_picture_on_a_model_without_vision_is_refused_up_front(env, monkeypatch):
    _ollama(env, "off")
    r = save(env, "photo.png", _png())
    seen = _fake_model(monkeypatch, [])
    events = _run(env, "make this bracket", reference=r["id"])
    assert [e["type"] for e in events] == ["error"]
    assert events[0]["kind"] == "reference" and "can't look at pictures" in events[0]["message"]
    assert seen == []  # no model call, no run recorded


def test_mesh_on_a_model_without_vision_gets_the_summary(env, monkeypatch):
    _ollama(env, "off")
    r = save(env, "part.stl", _stl())
    seen = _fake_model(monkeypatch, SUBMIT)
    events = _run(env, "a lid for this", reference=r["id"])
    assert events[-1]["type"] == "done"
    assert any(e["type"] == "notice" and "text summary" in e["message"] for e in events)
    content = seen[0][-1]["content"]
    assert isinstance(content, str) and "Size 20 x 10 x 5 mm" in content


def test_scad_reference_is_kept_apart_from_the_design_code(env, monkeypatch):
    _ollama(env, "off")
    src = "module knob() { cylinder(d=30, h=12); }\nknob();\n"
    r = save(env, "knob.scad", src.encode())
    seen = _fake_model(monkeypatch, SUBMIT + SUBMIT)
    first = _run(env, "a knob like this but 40 mm", reference=r["id"])
    content = seen[0][-1]["content"]
    assert "```openscad-reference\n" + src.strip() in content and "Current design code" not in content
    assert "not the code to edit" in content
    # a follow-up edits the design; the reference is only recalled by name and summary
    _run(env, "make it taller", design_id=first[-1]["design_id"])
    follow = seen[1]
    assert "(Attached reference: knob.scad" in follow[1]["content"]
    assert "```openscad-reference" not in json.dumps(follow)
    assert follow[-1]["content"].startswith("Current design code:\n```openscad\ncube([20,10,5]);")


