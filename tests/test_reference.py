def test_api(env, monkeypatch):
    from fastapi.testclient import TestClient

    from app import main, mcp_server

    importlib.reload(mcp_server)
    monkeypatch.setattr(main, "store", env.store)
    client = TestClient(main.app)
    _ollama(env, "on")

    r = client.post("/api/references?name=photo.png", content=_png(), headers={"content-type": "application/octet-stream"})
    assert r.status_code == 200, r.text
    ref = r.json()
    img = client.get(ref["image_url"])
    assert img.status_code == 200 and img.headers["content-type"] == "image/png" and img.content.startswith(b"\x89PNG")
    assert client.get("/api/references/ref_AAAAAAAAAAAAAAAA/image").status_code == 404

    assert client.post("/api/references?name=x.exe", content=b"MZ").status_code == 415
    assert client.post("/api/references?name=x.png", content=b"nope").json()["error"].startswith("That file is not a picture")
    big = b"x" * (env.ref.MAX_BYTES["scad"] + 1)
    assert client.post("/api/references?name=x.scad", content=big).status_code == 413

    _fake_model(monkeypatch, SUBMIT)
    lines = [json.loads(x) for x in client.post("/api/generate", json={"prompt": "make this", "reference": ref["id"]}).text.splitlines()]
    assert lines[-1]["type"] == "done"
    design = client.get(f"/api/designs/{lines[-1]['design_id']}").json()
    assert design["messages"][0]["reference"]["name"] == "photo.png"
