def _png(w=40, h=30) -> bytes:
    from PIL import Image

    buf = io.BytesIO()
    Image.new("RGB", (w, h), (200, 30, 30)).save(buf, "PNG")
    return buf.getvalue()


def _stl(extents=(20, 10, 5)) -> bytes:
    import trimesh

    return trimesh.creation.box(extents=extents).export(file_type="stl")


GCODE = "\n".join(
    ["; generated by PrusaSlicer 2.8.1", "G90", "M83", "G28", "G1 Z0.2 F600", "G1 X-5 Y-5 E2 ; purge"]
    + [line for z in (0.2, 0.4, 0.6) for line in (
        f"G1 Z{z}", "G0 X10 Y10", "G1 X50 Y10 E1.2", "G1 X50 Y30 E0.6", "G1 X10 Y30 E1.2", "G1 X10 Y10 E0.6", "G1 E-0.8")]
)


def save(env, name, data):
    return asyncio.run(env.ref.save(name, data))


# ---- analysis -----------------------------------------------------------------------
def test_picture(env):
    r = save(env, "bracket photo.JPG", _png(2000, 1000))
    assert r["kind"] == "image" and r["kind_label"] == "Picture" and r["id"].startswith("ref_")
    assert r["summary"] == "A picture, 2000 x 1000 px."
    assert r["image_url"] == f"/api/references/{r['id']}/image"
    full = env.ref.load(r["id"])
    from PIL import Image

    img = Image.open(io.BytesIO(base64.b64decode(full["image_b64"])))
    assert max(img.size) == env.ref.MAX_IMAGE_SIDE  # downscaled: fewer tokens


def test_mesh_summary_and_render(env):
    r = save(env, "part.stl", _stl((20, 10, 5)))
    assert r["kind"] == "mesh"
    assert "Size 20 x 10 x 5 mm" in r["summary"] and "volume 1.0 cm3" in r["summary"]
    assert r["image_url"]  # rendered with the same 4-view sheet the agent uses
    assert env.previews[-1].startswith('import("') and "mesh.stl" in env.previews[-1]
    assert env.ref.load(r["id"])["image_b64"] == base64.b64encode(FAKE_SHEET).decode()


