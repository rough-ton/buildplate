def test_gcode(env):
    r = save(env, "part.gcode", GCODE.encode())
    assert r["kind"] == "gcode"
    # extruding moves count (the purge line too); travel and retraction moves do not
    g = env.ref.parse_gcode(GCODE)
    assert g["layers"] == 3 and g["layer_height"] == 0.2
    assert g["min"][:2] == [-5, -5] and g["max"][:2] == [50, 30]
    assert "sliced with PrusaSlicer 2.8.1" in r["summary"] and "0.6 mm tall" in r["summary"]
    assert r["image_url"]


def test_rejects(env):
    with pytest.raises(env.ref.ReferenceError, match="Attach a picture"):
        save(env, "notes.pdf", b"%PDF")
    with pytest.raises(env.ref.ReferenceError, match="not a picture"):
        save(env, "x.png", b"not really")
    with pytest.raises(env.ref.ReferenceError, match="No printed moves"):
        save(env, "x.gcode", b"G28\nG0 X10\n")
    with pytest.raises(env.ref.ReferenceError, match="empty"):
        save(env, "x.stl", b"")
    assert not list((env.tmp / "references").glob("*"))  # nothing left behind
    assert env.ref.load("../../etc") is None and env.ref.load("ref_doesnotexist0000") is None


